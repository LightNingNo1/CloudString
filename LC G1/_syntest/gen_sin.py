import math

N = 4096
MAXA = 32767

def sval(A):
    x = MAXA * math.sin(2.0 * math.pi * A / N)
    if x >= 0:
        v = math.floor(x + 0.5)
    else:
        v = math.ceil(x - 0.5)
    return v & 0xFFFF

vals = [sval(A) for A in range(N)]

HEX = "0123456789ABCDEF"

def rows_for(inst):
    sh = 4 * inst
    rows = []
    for r in range(64):
        chars = []
        for p in range(63, -1, -1):
            ch = (vals[r * 64 + p] >> sh) & 0xF
            chars.append(HEX[ch])
        rows.append("".join(chars))
    return rows

lines = []
lines.append("//Copyright (C)2014-2024 Gowin Semiconductor Corporation.")
lines.append("//All rights reserved.")
lines.append("//File Title: IP file")
lines.append("//Tool Version: V1.9.10.02")
lines.append("//Part Number: GW2A-LV18PG256C8/I7")
lines.append("//Device: GW2A-18")
lines.append("//Device Version: C")
lines.append("//")
lines.append("//4096x16 pure sine LUT: value(A) = round(32767*sin(2*pi*A/4096)), 16-bit two's")
lines.append("//complement. A=0 -> 0, A=1024 -> +32767, A=2048 -> 0, A=3072 -> -32767.")
lines.append("//Generated by gen_sin.py (do not hand-edit the INIT_RAM rows).")
lines.append("")
lines.append("module Gowin_pROM_sin (dout, clk, oce, ce, reset, ad);")
lines.append("")
lines.append("output [15:0] dout;")
lines.append("input clk;")
lines.append("input oce;")
lines.append("input ce;")
lines.append("input reset;")
lines.append("input [11:0] ad;")
lines.append("")
for k in range(4):
    lines.append("wire [27:0] prom_inst_%d_dout_w;" % k)
lines.append("wire gw_gnd;")
lines.append("")
lines.append("assign gw_gnd = 1'b0;")
lines.append("")

for k in range(4):
    lo = 4 * k
    lines.append("pROM prom_inst_%d (" % k)
    lines.append("    .DO({prom_inst_%d_dout_w[27:0],dout[%d:%d]})," % (k, lo + 3, lo))
    lines.append("    .CLK(clk),")
    lines.append("    .OCE(oce),")
    lines.append("    .CE(ce),")
    lines.append("    .RESET(reset),")
    lines.append("    .AD({ad[11:0],gw_gnd,gw_gnd})")
    lines.append(");")
    lines.append("")
    lines.append("defparam prom_inst_%d.READ_MODE = 1'b1;" % k)
    lines.append("defparam prom_inst_%d.BIT_WIDTH = 4;" % k)
    lines.append('defparam prom_inst_%d.RESET_MODE = "SYNC";' % k)
    rows = rows_for(k)
    for r in range(64):
        lines.append("defparam prom_inst_%d.INIT_RAM_%02X = 256'h%s;" % (k, r, rows[r]))
    lines.append("")

lines.append("endmodule //Gowin_pROM_sin")
lines.append("")

out = r"d:\Gowin\LC G1\src\gowin_prom_sin.v"
with open(out, "w", newline="\n") as f:
    f.write("\n".join(lines))

