// ============================================================================
// led_driver.v - 6 路 LED 驱动
// ----------------------------------------------------------------------------
// 跟随各弦 ADSR 包络，有声音时点亮（板载 LED 低电平有效）。
// ============================================================================
module led_driver (
    input  wire [15:0] env0, env1, env2, env3, env4, env5,
    output wire [5:0]  led
);
    // 包络非零 -> 点亮（低电平有效）
    wire [5:0] active = { (env5 != 16'd0),
                          (env4 != 16'd0),
                          (env3 != 16'd0),
                          (env2 != 16'd0),
                          (env1 != 16'd0),
                          (env0 != 16'd0) };

    assign led = ~active;
endmodule