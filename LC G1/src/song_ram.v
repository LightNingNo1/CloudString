// ============================================================================
// song_ram.v - 在线下载曲目的存储（3 个下载槽 × 256 事件槽，可写）
// ----------------------------------------------------------------------------
// 事件格式（24 位，最多 2 音混音，与 song_player.v 的解码完全一致）：
//   [23:22] cnt1 = 目标音数-1（00=1 音、01=2 音）
//   [21:17] n0、[16:12] n1：至多 2 个目标弦号（0..31，全 32 弦）
//           （单音事件 n1 固定 0，播放器按 cnt1 屏蔽，不会误指 v0）
//   [11:0]  时值，单位 10ms（1..4095；0 = 曲终标记，读到后回曲首起始灯塔）
// 地址 [9:0] = {槽号[1:0], 槽内地址[7:0]}：3 槽 × 256 槽 = 768 深度，
// 每槽可存 255 个真实音符（slot 0..254）+ 1 个曲终标记（slot 255）。
// 由 ble_link.v 在手机下载时写入（BEGIN 帧指定槽号），由 song_player.v 读出
// 做 LED 指引（播放时按槽号寻址）。单时钟域单口 RAM。
// ============================================================================
module song_ram (
    input  wire        clk,
    input  wire        we,
    input  wire [9:0]  waddr,
    input  wire [23:0] wdata,
    input  wire [9:0]  raddr,
    output reg  [23:0] rdata
);
    reg [23:0] mem [0:767];
    integer i;

    initial begin
        for (i = 0; i < 768; i = i + 1)
            mem[i] = 24'h000000;      // 上电为空曲（读到时值 0 即曲终，指引不会乱亮）
    end

    always @(posedge clk) begin
        if (we)
            mem[waddr] <= wdata;
        rdata <= mem[raddr];
    end
endmodule
